import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { Light as SyntaxHighlighter } from 'react-syntax-highlighter';
import jsx from 'react-syntax-highlighter/dist/esm/languages/hljs/javascript';
import css from 'react-syntax-highlighter/dist/esm/languages/hljs/css';
import { atomOneDark } from 'react-syntax-highlighter/dist/esm/styles/hljs';
import {
  ArrowLeft, Code2, Loader2, Copy, Check, Download,
  RefreshCw, AlertCircle, Eye, EyeOff
} from 'lucide-react';
import { useAnalysis } from '../contexts/AnalysisContext';
import { codeGenApi } from '../services/api';

SyntaxHighlighter.registerLanguage('javascript', jsx);
SyntaxHighlighter.registerLanguage('css', css);

